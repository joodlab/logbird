import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { clips, MEDIA_ENCODING, screenshots, type Variant } from '../src/lib/media-manifest';

/**
 * The content version of every media file the site serves (src/lib/media-versions.ts): a short SHA-256 of each source
 * capture together with the encoder settings, so a replaced capture or a changed setting gives new URLs (`?v=`), and
 * the long media cache (Cache-Control on /media/*) can never serve old bytes under a page that describes new ones.
 * Keys: `<id>/<theme>` for screenshots (the phone capture is `<id>-phone/<theme>`), `<clip>.webm` and `<clip>-poster`.
 */
const root = resolve(import.meta.dirname, '../../..');
const encoding = JSON.stringify(MEDIA_ENCODING);
const digest = (bytes: Buffer, salt: string) => createHash('sha256').update(salt).update(bytes).digest('hex').slice(0, 10);

export async function computeMediaVersions() {
  const versions: Record<string, string> = {};
  const add = async (key: string, path: string, salt: string) => {
    versions[key] = digest(await readFile(resolve(root, path)), salt);
  };
  const variant = async (id: string, entry: Variant) => {
    for (const theme of ['light', 'dark'] as const) {
      const path = entry[theme];
      if (path) await add(`${id}/${theme}`, path, `${encoding}|${entry.width}x${entry.height}`);
    }
  };
  for (const entry of screenshots) {
    await variant(entry.id, entry);
    if (entry.phone) await variant(`${entry.id}-phone`, entry.phone);
  }
  for (const clip of clips) {
    await add(`${clip.id}.webm`, clip.src, 'copy');
    await add(`${clip.id}-poster`, clip.poster, encoding);
  }
  return Object.fromEntries(Object.entries(versions).sort(([a], [b]) => a.localeCompare(b)));
}

/** The generated module's text: one sorted entry per line, so a diff shows exactly which files changed. */
export function mediaVersionsModule(versions: Record<string, string>) {
  const lines = Object.entries(versions).map(([key, value]) => `  '${key}': '${value}',`);
  return `/** Generated by \`pnpm media:versions\` (scripts/media-versions.ts) from the media sources. Do not edit by hand. */
export const MEDIA_VERSIONS: Record<string, string> = {
${lines.join('\n')}
};
`;
}
