import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import sharp from 'sharp';
import { clips, MEDIA_ENCODING, screenshots, type Variant } from '../src/lib/media-manifest';

/**
 * Content versions for every file the site serves under a fixed name (src/lib/asset-versions.ts), so a file replaced in
 * place gets a new URL (`?v=`) and no cache (the CDN or a browser) can serve old bytes under a page that describes new
 * ones. Keys:
 * - `<id>/<theme>`, `<id>-phone/<theme>`, `<clip>.webm`, `<clip>-poster`: media, from the source capture, the encoder
 *   options (MEDIA_ENCODING, passed verbatim to the encoder) and the encoder's own versions (sharp, libvips, aom, webp),
 *   so a recapture, an option change or an encoder upgrade gives every affected file a new URL;
 * - `brand/<file>`: the files in public/brand, from their bytes;
 * - `site.webmanifest`: the manifest as written with its icons' versioned URLs.
 * OG_DESIGN_VERSION covers what scripts/og.ts and og-cards.ts draw besides the words: their code, the wordmark it embeds and the
 * renderer and font package versions. seo.ts combines it with each card's words.
 */
const app = resolve(import.meta.dirname, '..');
const root = resolve(app, '../..');
const require = createRequire(import.meta.url);
const short = (...parts: (string | Buffer)[]) => {
  const hash = createHash('sha256');
  for (const part of parts) hash.update(part).update('\0');
  return hash.digest('hex').slice(0, 10);
};
const { sharp: sharpVersion, vips, aom, webp, heif } = sharp.versions as Record<string, string>;
const encoder = JSON.stringify({ MEDIA_ENCODING, sharp: sharpVersion, vips, aom, webp, heif });

export async function computeAssetVersions() {
  const versions: Record<string, string> = {};
  const variant = async (id: string, entry: Variant) => {
    for (const theme of ['light', 'dark'] as const) {
      const path = entry[theme];
      if (path) versions[`${id}/${theme}`] = short(encoder, `${entry.width}x${entry.height}`, await readFile(resolve(root, path)));
    }
  };
  for (const entry of screenshots) {
    await variant(entry.id, entry);
    if (entry.phone) await variant(`${entry.id}-phone`, entry.phone);
  }
  for (const clip of clips) {
    versions[`${clip.id}.webm`] = short('copy', await readFile(resolve(root, clip.src)));
    versions[`${clip.id}-poster`] = short(encoder, await readFile(resolve(root, clip.poster)));
  }
  for (const file of (await readdir(resolve(app, 'public/brand'))).sort()) {
    versions[`brand/${file}`] = short(await readFile(resolve(app, 'public/brand', file)));
  }
  const manifest = JSON.parse(await readFile(resolve(app, 'public/site.webmanifest'), 'utf8')) as { icons: { src: string }[] };
  for (const icon of manifest.icons) {
    const file = icon.src.replace(/^\/brand\//, '').replace(/\?.*$/, '');
    const version = versions[`brand/${file}`];
    if (!version) throw new Error(`site.webmanifest names ${icon.src}, which is not in public/brand`);
    icon.src = `/brand/${file}?v=${version}`;
  }
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  versions['site.webmanifest'] = short(manifestText);
  return { versions: Object.fromEntries(Object.entries(versions).sort(([a], [b]) => a.localeCompare(b))), manifestText };
}

export async function computeOgDesignVersion() {
  const packages = ['satori', '@resvg/resvg-js', '@fontsource/geist', '@fontsource/geist-mono'].map(
    (name) => `${name}@${(require(`${name}/package.json`) as { version: string }).version}`,
  );
  return short(
    await readFile(resolve(app, 'scripts/og.ts')),
    await readFile(resolve(app, 'scripts/og-cards.ts')),
    await readFile(resolve(app, 'public/brand/logbird-wordmark-dark.svg')),
    packages.join(','),
  );
}

/** The generated module's text: one sorted entry per line, so a diff shows exactly which files changed. */
export function assetVersionsModule(versions: Record<string, string>, ogDesign: string) {
  const lines = Object.entries(versions).map(([key, value]) => `  '${key}': '${value}',`);
  return `/** Generated by \`pnpm assets:versions\` (scripts/asset-versions.ts). Do not edit by hand. */
export const ASSET_VERSIONS: Record<string, string> = {
${lines.join('\n')}
};

/** What scripts/og.ts draws besides each card's words (its code, the wordmark, renderer and font versions). */
export const OG_DESIGN_VERSION = '${ogDesign}';
`;
}
