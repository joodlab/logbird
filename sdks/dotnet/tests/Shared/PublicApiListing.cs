using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.Versioning;
using System.Text;

namespace Logbird.ApiBaseline;

/// <summary>
/// Writes the public surface of an assembly as plain text, one line per type and member: every public type, its
/// public and protected members with their signatures, enum values, constants, optional-parameter defaults and the
/// default values of public settable properties of types with a public parameterless constructor. The committed
/// baseline files under <c>sdks/dotnet/api</c> are this listing; a test fails when the built surface differs, so a change
/// to the public API is always a visible change to one of those files.
/// </summary>
internal static class PublicApiListing
{
    private const BindingFlags Declared = BindingFlags.DeclaredOnly | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static;

    /// <summary>The target framework the assembly was built for, as a folder-style moniker (net8.0, netstandard2.0).</summary>
    public static string TargetOf(Assembly assembly)
    {
        var name = assembly.GetCustomAttribute<TargetFrameworkAttribute>()?.FrameworkName ?? "unknown";
        var framework = new System.Runtime.Versioning.FrameworkName(name);
        return framework.Identifier switch
        {
            ".NETStandard" => "netstandard" + framework.Version.ToString(2),
            ".NETCoreApp" => "net" + framework.Version.ToString(2),
            ".NETFramework" => "net" + framework.Version.ToString(3).Replace(".", string.Empty),
            _ => name,
        };
    }

    /// <summary>The committed baseline for an assembly and target, found by walking up to the repository's sdks/dotnet.</summary>
    public static string BaselinePath(Assembly assembly)
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Logbird.slnx")))
        {
            directory = directory.Parent;
        }

        if (directory is null)
        {
            throw new InvalidOperationException("Could not find sdks/dotnet (Logbird.slnx) above " + AppContext.BaseDirectory);
        }

        return Path.Combine(directory.FullName, "api", assembly.GetName().Name + "." + TargetOf(assembly) + ".txt");
    }

    /// <summary>
    /// Fails when the built public surface differs from the committed baseline. With LOGBIRD_UPDATE_PUBLIC_API=1 it
    /// rewrites the baseline instead, so an intended change is one deliberate, reviewable edit to that file.
    /// </summary>
    public static void Verify(Assembly assembly)
    {
        var listing = Of(assembly);
        var path = BaselinePath(assembly);
        if (Environment.GetEnvironmentVariable("LOGBIRD_UPDATE_PUBLIC_API") == "1")
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, listing, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            return;
        }

        if (!File.Exists(path))
        {
            Assert.Fail($"No public API baseline at {path}. Run the tests with LOGBIRD_UPDATE_PUBLIC_API=1 and commit the file.");
        }

        var expected = File.ReadAllText(path).Replace("\r\n", "\n");
        if (expected == listing)
        {
            return;
        }

        var before = expected.Split('\n');
        var after = listing.Split('\n');
        var removed = before.Except(after).Take(20).Select(l => "- " + l);
        var added = after.Except(before).Take(20).Select(l => "+ " + l);
        Assert.Fail(
            $"The public API of {assembly.GetName().Name} ({TargetOf(assembly)}) differs from {path}.\n"
            + "If the change is intended, run the tests with LOGBIRD_UPDATE_PUBLIC_API=1 and commit the updated baseline; it is the record of the public API.\n"
            + string.Join("\n", removed.Concat(added)));
    }

    /// <summary>The listing, with LF line endings.</summary>
    public static string Of(Assembly assembly)
    {
        var text = new StringBuilder();
        text.Append("# Public API of ").Append(assembly.GetName().Name).Append(" (").Append(TargetOf(assembly)).Append(")\n");
        text.Append("# Generated by tests/Shared/PublicApiListing.cs; regenerate with LOGBIRD_UPDATE_PUBLIC_API=1 dotnet test.\n");
#if NET
        text.Append("# Members are sorted by name. Reference types show their nullability annotations (T? may be null).\n");
#else
        text.Append("# Members are sorted by name. Nullability annotations are not shown: this listing comes from the .NET Framework\n");
        text.Append("# run, which cannot read them; the net8.0 listing shows them for the same source.\n");
#endif
        foreach (var type in assembly.GetExportedTypes().OrderBy(t => t.FullName, StringComparer.Ordinal))
        {
            text.Append('\n');
            WriteType(text, type);
        }

        return text.ToString();
    }

    private static void WriteType(StringBuilder text, Type type)
    {
        text.Append(TypeHeader(type)).Append('\n');
        if (type.IsEnum)
        {
            foreach (var field in type.GetFields(BindingFlags.Public | BindingFlags.Static).OrderBy(f => Convert.ToInt64(f.GetRawConstantValue(), CultureInfo.InvariantCulture)).ThenBy(f => f.Name, StringComparer.Ordinal))
            {
                text.Append("  ").Append(field.Name).Append(" = ").Append(Convert.ToString(field.GetRawConstantValue(), CultureInfo.InvariantCulture)).Append('\n');
            }

            return;
        }

        if (typeof(Delegate).IsAssignableFrom(type))
        {
            var invoke = type.GetMethod("Invoke")!;
            text.Append("  delegate ").Append(Name(invoke.ReturnType)).Append(" Invoke(").Append(Parameters(invoke)).Append(")\n");
            return;
        }

        var lines = new List<(string Key, string Line)>();
        foreach (var constructor in type.GetConstructors(Declared).Where(Visible))
        {
            lines.Add(("", "  " + Access(constructor) + "ctor(" + Parameters(constructor) + ")"));
        }

        foreach (var field in type.GetFields(Declared).Where(f => Visible(f) && !f.IsSpecialName && !IsCompilerGenerated(f.Name)))
        {
            var line = "  " + Access(field) + (field.IsLiteral ? "const " : (field.IsStatic ? "static " : string.Empty) + (field.IsInitOnly ? "readonly " : string.Empty))
                + FieldType(field) + " " + field.Name;
            if (field.IsLiteral)
            {
                line += " = " + Literal(field.GetRawConstantValue());
            }

            lines.Add((field.Name, line));
        }

        foreach (var property in type.GetProperties(Declared))
        {
            var getter = property.GetMethod is { } g && Visible(g) ? g : null;
            var setter = property.SetMethod is { } s && Visible(s) ? s : null;
            if (getter is null && setter is null)
            {
                continue;
            }

            var accessor = getter ?? setter!;
            var indexParameters = property.GetIndexParameters();
            var name = indexParameters.Length == 0 ? property.Name : "this[" + string.Join(", ", indexParameters.Select(Parameter)) + "]";
            var accessors = (getter is null ? string.Empty : "get; ")
                + (setter is null ? string.Empty : (IsInitOnly(setter) ? "init; " : "set; "));
            lines.Add((property.Name, "  " + Access(accessor) + Modifiers(accessor) + "property " + PropertyType(property) + " " + name + " { " + accessors + "}"));
        }

        foreach (var evt in type.GetEvents(Declared))
        {
            var add = evt.AddMethod;
            if (add is not null && Visible(add))
            {
                lines.Add((evt.Name, "  " + Access(add) + Modifiers(add) + "event " + Name(evt.EventHandlerType!) + " " + evt.Name));
            }
        }

        foreach (var method in type.GetMethods(Declared).Where(m => Visible(m) && (!m.IsSpecialName || m.Name.StartsWith("op_", StringComparison.Ordinal)) && !IsCompilerGenerated(m.Name)))
        {
            var generic = method.IsGenericMethodDefinition ? "<" + string.Join(", ", method.GetGenericArguments().Select(a => a.Name)) + ">" : string.Empty;
            lines.Add((method.Name, "  " + Access(method) + Modifiers(method) + "method " + ReturnType(method) + " " + method.Name + generic + "(" + Parameters(method) + ")"));
        }

        foreach (var (_, line) in lines.OrderBy(l => l.Key, StringComparer.Ordinal).ThenBy(l => l.Line, StringComparer.Ordinal))
        {
            text.Append(line).Append('\n');
        }

        foreach (var line in Defaults(type))
        {
            text.Append(line).Append('\n');
        }
    }

    /// <summary>The values a new instance starts with, for types a caller creates and then configures.</summary>
    private static IEnumerable<string> Defaults(Type type)
    {
        if (type.IsAbstract || type.IsGenericTypeDefinition || type.IsInterface || type.GetConstructor(Type.EmptyTypes) is not { IsPublic: true } constructor)
        {
            yield break;
        }

        object instance;
        try
        {
            instance = constructor.Invoke(null);
        }
        catch (TargetInvocationException)
        {
            yield break;
        }

        var lines = new List<string>();
        foreach (var property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (property.GetMethod is not { IsPublic: true } || property.SetMethod is not { IsPublic: true } || property.GetIndexParameters().Length > 0 || !IsSimple(property.PropertyType))
            {
                continue;
            }

            object? value;
            try
            {
                value = property.GetValue(instance);
            }
            catch (TargetInvocationException)
            {
                continue;
            }

            lines.Add("  default " + property.Name + " = " + Literal(value));
        }

        lines.Sort(StringComparer.Ordinal);
        foreach (var line in lines)
        {
            yield return line;
        }

        (instance as IDisposable)?.Dispose();
    }

    private static bool IsSimple(Type type)
    {
        var t = Nullable.GetUnderlyingType(type) ?? type;
        return t.IsPrimitive || t.IsEnum || t == typeof(string) || t == typeof(decimal) || t == typeof(TimeSpan) || t == typeof(Uri);
    }

    private static string TypeHeader(Type type)
    {
        var kind = type.IsEnum ? "enum"
            : type.IsInterface ? "interface"
            : typeof(Delegate).IsAssignableFrom(type) ? "delegate"
            : type.IsValueType ? (IsRecord(type) ? "record struct" : "struct")
            : IsRecord(type) ? "record"
            : "class";
        var modifiers = type.IsClass && !typeof(Delegate).IsAssignableFrom(type)
            ? type.IsAbstract && type.IsSealed ? "static " : type.IsAbstract ? "abstract " : type.IsSealed ? "sealed " : string.Empty
            : string.Empty;
        var header = (type.IsNestedFamily || type.IsNestedFamORAssem ? "protected " : "public ") + modifiers + kind + " " + Name(type, full: true);
        var bases = new List<string>();
        if (type.IsEnum)
        {
            bases.Add(Name(Enum.GetUnderlyingType(type)));
        }
        else if (type.BaseType is { } baseType && baseType != typeof(object) && baseType != typeof(ValueType) && !typeof(Delegate).IsAssignableFrom(type))
        {
            bases.Add(Name(baseType));
        }

        if (!type.IsEnum && !typeof(Delegate).IsAssignableFrom(type))
        {
            var inherited = type.BaseType?.GetInterfaces() ?? Type.EmptyTypes;
            bases.AddRange(type.GetInterfaces().Where(i => i.IsPublic || i.IsNestedPublic).Where(i => !inherited.Contains(i)).Select(i => Name(i)).OrderBy(n => n, StringComparer.Ordinal));
        }

        return bases.Count == 0 ? header : header + " : " + string.Join(", ", bases);
    }

    private static bool IsRecord(Type type) => type.GetMethod("<Clone>$", BindingFlags.Public | BindingFlags.Instance) is not null
        || (type.IsValueType && type.GetMethod("PrintMembers", BindingFlags.NonPublic | BindingFlags.Instance) is not null);

    private static bool Visible(MethodBase method) => method.IsPublic || method.IsFamily || method.IsFamilyOrAssembly;

    private static bool Visible(FieldInfo field) => field.IsPublic || field.IsFamily || field.IsFamilyOrAssembly;

    private static bool IsCompilerGenerated(string name) => name.Any(c => c == '<');

    private static string Access(MethodBase method) => method.IsPublic ? string.Empty : "protected ";

    private static string Access(FieldInfo field) => field.IsPublic ? string.Empty : "protected ";

    private static string Modifiers(MethodInfo method)
    {
        if (method.IsStatic)
        {
            return "static ";
        }

        if (method.DeclaringType!.IsInterface)
        {
            return string.Empty;
        }

        if (method.IsAbstract)
        {
            return "abstract ";
        }

        if (method.IsVirtual && !method.IsFinal)
        {
            return method.GetBaseDefinition().DeclaringType == method.DeclaringType ? "virtual " : "override ";
        }

        return method.IsVirtual && method.GetBaseDefinition().DeclaringType != method.DeclaringType ? "sealed override " : string.Empty;
    }

    private static bool IsInitOnly(MethodInfo setter)
        => setter.ReturnParameter.GetRequiredCustomModifiers().Any(m => m.FullName == "System.Runtime.CompilerServices.IsExternalInit");

    private static string Parameters(MethodBase method) => string.Join(", ", method.GetParameters().Select(Parameter));

    private static string Parameter(ParameterInfo parameter)
    {
        var type = parameter.ParameterType;
        var prefix = string.Empty;
        if (type.IsByRef)
        {
            type = type.GetElementType()!;
            prefix = parameter.IsOut ? "out " : parameter.IsIn ? "in " : "ref ";
        }
        else if (parameter.GetCustomAttributes(typeof(ParamArrayAttribute), false).Length > 0)
        {
            prefix = "params ";
        }

        var text = prefix + ParameterType(parameter, type) + " " + parameter.Name;
        if (parameter.HasDefaultValue)
        {
            text += " = " + Literal(parameter.RawDefaultValue);
        }

        return text;
    }

#if NET
    private static readonly NullabilityInfoContext Nullability = new();

    private static string PropertyType(PropertyInfo property) => Name(property.PropertyType, Nullability.Create(property));

    private static string FieldType(FieldInfo field) => Name(field.FieldType, Nullability.Create(field));

    private static string ReturnType(MethodInfo method) => Name(method.ReturnType, Nullability.Create(method.ReturnParameter));

    private static string ParameterType(ParameterInfo parameter, Type type) => Name(type, Nullability.Create(parameter), byRefElement: parameter.ParameterType.IsByRef);

    /// <summary>A type name with its nullability annotations, nested into generic arguments and array elements.</summary>
    private static string Name(Type type, NullabilityInfo info, bool byRefElement = false)
    {
        if (byRefElement && info.ElementType is { } element)
        {
            info = element;
        }

        if (type.IsArray && info.ElementType is { } arrayElement)
        {
            var array = Name(type.GetElementType()!, arrayElement) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
            return array + Mark(type, info);
        }

        if (type.IsGenericType && Nullable.GetUnderlyingType(type) is null && info.GenericTypeArguments.Length == type.GetGenericArguments().Length)
        {
            var plain = Name(type.GetGenericTypeDefinition());
            var open = plain.IndexOf('<', StringComparison.Ordinal);
            var stem = open >= 0 ? plain.Substring(0, open) : plain;
            var arguments = type.GetGenericArguments().Select((a, i) => Name(a, info.GenericTypeArguments[i]));
            return stem + "<" + string.Join(", ", arguments) + ">" + Mark(type, info);
        }

        return Name(type) + Mark(type, info);
    }

    private static string Mark(Type type, NullabilityInfo info)
        => !type.IsValueType && (info.ReadState == NullabilityState.Nullable || (info.ReadState == NullabilityState.Unknown && info.WriteState == NullabilityState.Nullable)) ? "?" : string.Empty;
#else
    private static string PropertyType(PropertyInfo property) => Name(property.PropertyType);

    private static string FieldType(FieldInfo field) => Name(field.FieldType);

    private static string ReturnType(MethodInfo method) => Name(method.ReturnType);

    private static string ParameterType(ParameterInfo parameter, Type type) => Name(type);
#endif

    private static string Literal(object? value) => value switch
    {
        null => "null",
        DBNull => "null",
        string s => "\"" + s + "\"",
        bool b => b ? "true" : "false",
        TimeSpan t => t.ToString("c", CultureInfo.InvariantCulture),
        Enum e => e.GetType().Name + "." + e,
        IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
        _ => value.ToString() ?? "null",
    };

    private static string Name(Type type, bool full = false)
    {
        if (type.IsByRef)
        {
            return Name(type.GetElementType()!, full) + "&";
        }

        if (type.IsArray)
        {
            return Name(type.GetElementType()!, full) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
        }

        if (type.IsPointer)
        {
            return Name(type.GetElementType()!, full) + "*";
        }

        if (type.IsGenericParameter)
        {
            return type.Name;
        }

        if (Nullable.GetUnderlyingType(type) is { } underlying)
        {
            return Name(underlying, full) + "?";
        }

        var keyword = Keyword(type);
        if (keyword is not null)
        {
            return keyword;
        }

        var name = type.Name;
        var tick = name.IndexOf('`');
        if (tick >= 0)
        {
            name = name.Substring(0, tick);
        }

        if (type.IsNested)
        {
            name = Name(type.DeclaringType!, full) + "." + name;
        }
        else if (full || !(type.Namespace ?? string.Empty).StartsWith("Logbird", StringComparison.Ordinal))
        {
            name = (type.Namespace is null ? string.Empty : type.Namespace + ".") + name;
        }

        if (type.IsGenericType)
        {
            var arguments = type.GetGenericArguments();
            if (type.IsNested)
            {
                // Arguments of the declaring type were already written with it.
                arguments = arguments.Skip(type.DeclaringType!.GetGenericArguments().Length).ToArray();
            }

            if (arguments.Length > 0)
            {
                name += "<" + string.Join(", ", arguments.Select(a => Name(a))) + ">";
            }
        }

        return name;
    }

    private static string? Keyword(Type type)
    {
        if (type == typeof(void)) { return "void"; }
        if (type == typeof(object)) { return "object"; }
        if (type == typeof(string)) { return "string"; }
        if (type == typeof(bool)) { return "bool"; }
        if (type == typeof(byte)) { return "byte"; }
        if (type == typeof(sbyte)) { return "sbyte"; }
        if (type == typeof(short)) { return "short"; }
        if (type == typeof(ushort)) { return "ushort"; }
        if (type == typeof(int)) { return "int"; }
        if (type == typeof(uint)) { return "uint"; }
        if (type == typeof(long)) { return "long"; }
        if (type == typeof(ulong)) { return "ulong"; }
        if (type == typeof(float)) { return "float"; }
        if (type == typeof(double)) { return "double"; }
        if (type == typeof(decimal)) { return "decimal"; }
        if (type == typeof(char)) { return "char"; }
        return null;
    }
}
