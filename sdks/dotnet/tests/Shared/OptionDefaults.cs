using System;
using System.Collections;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

namespace Logbird.ApiBaseline;

/// <summary>
/// The defaults a caller starts from, for an explicit list of audited option types. They sit next to each project's
/// PublicAPI files as PublicAPI.Defaults.txt, which the public API analyzer cannot record. Every public instance
/// property of each listed type is printed, nested listed types included; a value of a kind with no format here fails
/// the test instead of being skipped, so no default can change unseen.
/// </summary>
internal static class OptionDefaults
{
    public static string Describe(IReadOnlyList<Type> audited)
    {
        var text = new StringBuilder();
        text.Append("# Defaults of the public option types: a new instance of each, every public property.\n");
        text.Append("# Generated by tests/Shared/OptionDefaults.cs; regenerate with LOGBIRD_UPDATE_PUBLIC_API=1 dotnet test (never in CI).\n");
        foreach (var type in audited.OrderBy(t => t.FullName, StringComparer.Ordinal))
        {
            var instance = Activator.CreateInstance(type)
                ?? throw new InvalidOperationException(type.FullName + " could not be created");
            text.Append('\n').Append(type.FullName).Append('\n');
            foreach (var line in Properties(instance, audited, "  "))
            {
                text.Append(line).Append('\n');
            }
        }

        return text.ToString();
    }

    /// <summary>
    /// Fails when the defaults differ from the committed file. LOGBIRD_UPDATE_PUBLIC_API=1 rewrites it instead, outside CI
    /// only, from the .NET 8 run only (the other runs verify the same file).
    /// </summary>
    public static void Verify(string projectDirectoryName, IReadOnlyList<Type> audited)
    {
        var listing = Describe(audited);
        var path = Path.Combine(SdkDirectory(), "src", projectDirectoryName, "PublicAPI.Defaults.txt");
        if (Environment.GetEnvironmentVariable("LOGBIRD_UPDATE_PUBLIC_API") == "1")
        {
            Assert.False(Environment.GetEnvironmentVariable("CI") == "true", "LOGBIRD_UPDATE_PUBLIC_API must not be set in CI: the defaults file is verified there, never written.");
#if NET8_0
            File.WriteAllText(path, listing, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
            return;
#endif
            // The other targets never write: they verify the same file below, so an update run cannot pass vacuously there.
        }

        Assert.True(File.Exists(path), $"No defaults record at {path}. Run the tests with LOGBIRD_UPDATE_PUBLIC_API=1 and commit the file.");

        // Values are written as escaped literals, so no line break inside a value can be hidden by this normalization.
        var expected = File.ReadAllText(path).Replace("\r\n", "\n");
        if (expected == listing)
        {
            return;
        }

        var before = expected.Split('\n');
        var after = listing.Split('\n');
        var first = Enumerable.Range(0, Math.Max(before.Length, after.Length)).First(i => i >= before.Length || i >= after.Length || before[i] != after[i]);
        Assert.Fail(
            $"The option defaults differ from {path} at line {first + 1}:\n"
            + $"- {(first < before.Length ? before[first] : "(end of file)")}\n"
            + $"+ {(first < after.Length ? after[first] : "(end of file)")}\n"
            + "If the change is intended, run the tests with LOGBIRD_UPDATE_PUBLIC_API=1 and commit the updated file.");
    }

    private static IEnumerable<string> Properties(object instance, IReadOnlyList<Type> audited, string indent)
    {
        foreach (var property in instance.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(p => p.GetMethod is { IsPublic: true } && p.GetIndexParameters().Length == 0)
            .OrderBy(p => p.Name, StringComparer.Ordinal))
        {
            var value = property.GetValue(instance);
            if (value is not null && audited.Contains(value.GetType()))
            {
                yield return indent + property.Name + " =";
                foreach (var line in Properties(value, audited, indent + "  "))
                {
                    yield return line;
                }
            }
            else
            {
                yield return indent + property.Name + " = " + Format(value, property.PropertyType);
            }
        }
    }

    private static string Format(object? value, Type declared)
    {
        switch (value)
        {
            case null:
                return "null";
            case string s:
                return Literal(s);
            case char c:
                return "'" + Escape(c.ToString()) + "'";
            case bool b:
                return b ? "true" : "false";
            case Enum e:
                return e.GetType().Name + "." + e.ToString().Replace(", ", " | " + e.GetType().Name + ".");
            case TimeSpan t:
                return "TimeSpan " + t.ToString("c", CultureInfo.InvariantCulture);
            case DateTimeOffset d:
                return "DateTimeOffset " + d.ToString("o", CultureInfo.InvariantCulture);
            case DateTime d:
                return "DateTime " + d.ToString("o", CultureInfo.InvariantCulture) + " " + d.Kind;
            case Uri u:
                return "Uri " + Literal(u.OriginalString);
            case Regex r:
                return "Regex " + Literal(r.ToString()) + " options " + r.Options + " timeout "
                    + (r.MatchTimeout == Regex.InfiniteMatchTimeout ? "infinite" : r.MatchTimeout.ToString("c", CultureInfo.InvariantCulture));
            case Delegate d:
                return "delegate " + d.Method.DeclaringType?.FullName + "." + d.Method.Name;
            case double x:
                return x.ToString("R", CultureInfo.InvariantCulture);
            case float x:
                return x.ToString("R", CultureInfo.InvariantCulture);
            case decimal x:
                return x.ToString(CultureInfo.InvariantCulture) + "m";
            case IEnumerable items:
                // Whether a caller can change the collection is part of the default, not only its elements.
                var mutability = value is IList list ? (list.IsReadOnly ? "read-only " : "mutable ")
                    : value.GetType().GetInterfaces().Any(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(ICollection<>))
                        ? ((bool)value.GetType().GetInterfaces().First(i => i.IsGenericType && i.GetGenericTypeDefinition() == typeof(ICollection<>)).GetProperty("IsReadOnly")!.GetValue(value)! ? "read-only " : "mutable ")
                        : string.Empty;
                return mutability + value.GetType().Name.Split('`')[0] + " [" + string.Join(", ", items.Cast<object?>().Select(i => Format(i, typeof(object)))) + "]";
        }

        if (value.GetType().IsPrimitive)
        {
            return Convert.ToString(value, CultureInfo.InvariantCulture)!;
        }

        throw new InvalidOperationException($"No format for a default of type {value.GetType().FullName} (declared {declared.FullName}); add one to OptionDefaults.Format or list the type as audited.");
    }

    private static string Literal(string s) => "\"" + Escape(s) + "\"";

    private static string Escape(string s)
    {
        var builder = new StringBuilder(s.Length);
        foreach (var c in s)
        {
            switch (c)
            {
                case '\\': builder.Append("\\\\"); break;
                case '"': builder.Append("\\\""); break;
                case '\'': builder.Append("\\'"); break;
                case '\n': builder.Append("\\n"); break;
                case '\r': builder.Append("\\r"); break;
                case '\t': builder.Append("\\t"); break;
                case '\0': builder.Append("\\0"); break;
                default:
                    if (c < 0x20 || c > 0x7E)
                    {
                        builder.Append("\\u").Append(((int)c).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(c);
                    }

                    break;
            }
        }

        return builder.ToString();
    }

    private static string SdkDirectory()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "Logbird.slnx")))
        {
            directory = directory.Parent;
        }

        return directory?.FullName ?? throw new InvalidOperationException("Could not find sdks/dotnet (Logbird.slnx) above " + AppContext.BaseDirectory);
    }
}
