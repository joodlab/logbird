import { readFile, writeFile } from 'node:fs/promises';

// Keep the migration authoritative while making compiled runtimes independent
// of their output directory and external SQL files.
const sql = (await readFile(new URL('../migrations/002_rollups.sql', import.meta.url), 'utf8')).replaceAll('\r\n', '\n').trim();
const literal = sql.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
await writeFile(
  new URL('../src/rollup-sql.ts', import.meta.url),
  `// Generated by scripts/generate-rollup-sql.mjs from migrations/002_rollups.sql.\nexport const rollupSql = \`\n${literal}\n\`;\n`,
);
